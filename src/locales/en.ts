/** Every language's words: the shape of the English ones. */
type Shape<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends (...a: infer A) => infer R
      ? (...a: A) => R
      : T[K] extends readonly (infer E)[]
        ? Shape<E>[]
        : Shape<T[K]>
}
export type Messages = Shape<typeof en>
